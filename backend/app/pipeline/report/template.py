"""Markdown report template (no LLM required)."""

from __future__ import annotations

import json
from datetime import UTC, datetime

from app.store import duck


def render(incident_id: str) -> str:
    """Render a comprehensive Markdown incident report from stored data."""
    inc = duck.get_incident(incident_id)
    if not inc:
        return f"# Incident Not Found\n\nID: {incident_id}"

    hosts = json.loads(inc["hosts"]) if isinstance(inc["hosts"], str) else inc["hosts"]
    techniques = json.loads(inc["techniques"]) if isinstance(inc["techniques"], str) else inc["techniques"]
    steps = json.loads(inc["steps"]) if isinstance(inc["steps"], str) else inc["steps"]
    users = json.loads(inc["users"]) if isinstance(inc["users"], str) else inc["users"]
    src_ips = json.loads(inc["src_ips"]) if isinstance(inc["src_ips"], str) else inc["src_ips"]

    risk_score = float(inc.get("risk_score", 0.0) or 0.0)
    det_count = int(inc.get("detection_count", len(inc.get("detection_ids", []))) or 0)
    ev_count = int(inc.get("event_count", 0) or 0)

    lines: list[str] = [
        f"# Incident Report: {inc['title']}",
        "",
        f"**Incident ID:** `{incident_id}`  ",
        f"**Risk Score:** {risk_score:.1f}/10.0  ",
        f"**Severity:** {inc['severity']}/10  ",
        f"**Status:** {inc['status']}  ",
        f"**Detections Merged:** {det_count}  ",
        f"**Raw Events Merged:** {ev_count}  ",
        f"**First seen:** {inc['first_seen']}  ",
        f"**Last seen:** {inc['last_seen']}  ",
        "",
        "## Affected Entities",
        "",
        f"- **Hosts:** {', '.join(hosts) or 'none'}",
        f"- **Users:** {', '.join(users) or 'none'}",
        f"- **Source IPs:** {', '.join(src_ips) or 'none'}",
        "",
        "## Kill Chain Progression",
        "",
    ]

    for step in steps:
        order = step.get("step_order", "?")
        t_id = step.get("technique_id", "?")
        tactic = step.get("tactic", "?")
        stage = step.get("kill_chain_stage") or tactic
        lines.append(f"### Step {order}: `{t_id}` – {tactic} ({stage})")
        lines.append(f"- **First seen:** {step.get('first_seen', '?')}")
        lines.append(f"- **Last seen:** {step.get('last_seen', '?')}")
        lines.append(f"- **Target Hosts:** {', '.join(step.get('hosts', [])) or 'none'}")
        lines.append("")

    lines += [
        "## Techniques (Chronological)",
        "",
        "\n".join(f"- `{t}`" for t in techniques) if techniques else "None recorded",
        "",
    ]

    # Reach analysis section
    reach_row = duck.get_incident_next(incident_id)
    if reach_row:
        reach_data = json.loads(reach_row["data"]) if isinstance(reach_row["data"], str) else reach_row["data"]
        blast = reach_data.get("blast_radius", {})
        crit_assets = blast.get("critical_assets_reached", [])
        crit_str = ", ".join(crit_assets) if crit_assets else "none"

        lines += [
            "## Blast Radius & Potential Next Reach",
            "",
            f"- **Potentially Reachable Hosts:** {blast.get('hosts_count', 0)}",
            f"- **Potentially Reachable Users:** {blast.get('users_count', 0)}",
            f"- **Critical Assets Exposed:** {crit_str}",
            "",
            "### Reachable Targets & Movement Vectors",
            "",
        ]

        targets = reach_data.get("reachable_targets", [])
        if targets:
            lines.append("| Target | Kind | Hops | Priority | Movement Vector / Reason |")
            lines.append("|---|---|---|---|---|")
            for tgt in targets[:15]:
                lines.append(
                    f"| `{tgt.get('target_label')}` | {tgt.get('target_kind')} | {tgt.get('hops')} | "
                    f"**{tgt.get('priority')}** | {tgt.get('reason')} |"
                )
            lines.append("")
        else:
            lines.append("No outgoing lateral reach observed.\n")

        if reach_data.get("disclaimer"):
            lines.append(f"> *{reach_data['disclaimer']}*\n")

    lines.append(f"---\n*Generated by CaseFile at {datetime.now(UTC).isoformat()}*")
    return "\n".join(lines)
